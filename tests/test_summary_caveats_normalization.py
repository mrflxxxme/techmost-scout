"""Нормализация списка оговорок при сравнении правки эксперта (Э4-П10, П-12).

Аудит нашёл дыру: мутация `_normalize_caveats` → `list(caveats)` (без `strip`
и без отсева пустых строк) переживала весь набор — от неё зависит, считается
ли правка эксперта из формы правкой (`resolve_summary_edit`), но сама функция
нормализации нигде не проверялась напрямую. Слой чистый: без БД и без сети
(инвариант №7).
"""

from __future__ import annotations

from app.summary_overrides import _normalize_caveats


def test_normalize_caveats_убирает_пробелы_по_краям():
    """Пробелы по краям каждой строки не должны превращать «то же самое» в правку."""
    assert _normalize_caveats(["  Оговорка первая  ", "Оговорка вторая"]) == [
        "Оговорка первая",
        "Оговорка вторая",
    ]


def test_normalize_caveats_отсеивает_пустые_строки():
    """Пустая строка (в том числе из одних пробелов) не считается оговоркой."""
    assert _normalize_caveats(["Оговорка", "", "   ", "Вторая"]) == ["Оговорка", "Вторая"]


def test_normalize_caveats_совпадает_с_нетронутым_списком():
    """Список уже без лишних пробелов и пустых строк нормализация не меняет."""
    assert _normalize_caveats(["Оговорка первая", "Оговорка вторая"]) == [
        "Оговорка первая",
        "Оговорка вторая",
    ]


def test_normalize_caveats_отличает_пробельную_правку_от_настоящей():
    """Мутация `list(caveats)` без `strip`/отсева даёт разные списки там, где по
    смыслу правки нет — именно это ловит эту мутацию: до нормализации списки
    не равны побайтово, после — равны."""
    submitted = ["  Оговорка  ", "", "Вторая"]
    original = ["Оговорка", "Вторая"]

    assert submitted != original
    assert _normalize_caveats(submitted) == _normalize_caveats(original)
