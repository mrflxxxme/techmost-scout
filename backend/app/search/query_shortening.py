"""Укорачивание длинной формулировки поиска — общий приём трёх адаптеров.

Диагноз Э2-Ж/З-6: у КиберЛенинки, Роспатента и arXiv длинная формулировка
модели «пере-уточняет» выдачу источника до пустой или почти пустой (found=0
у первых двух, found=0 у arXiv на семи и более словах через булев `AND`).
Починка везде одна: при бедной выдаче на исходном тексте — ОДИН повтор с
укороченной формой, детерминированно (без модели), один и тот же вход всегда
даёт один и тот же короткий запрос. Каждый адаптер решает САМ, когда повтор
нужен (found==0 у КиберЛенинки и arXiv, `< 3` кандидатов у Роспатента —
у него переуточнение душит не до нуля) — этот модуль отвечает только за то,
из чего складывается короткая форма, а не за то, когда её просить.

Русский и английский варианты не переиспользуют друг друга: у русского
исходный регистр и пунктуация токена сохраняются (сравнение со стоп-словами
идёт по очищенной копии), у английского текст сразу разбирается на голые
слова в нижнем регистре и короткие слова (< 3 букв) тоже отсеиваются — так
было до дробления (arXiv, `_content_words`), поведение не менялось.
"""

from __future__ import annotations

import re

#: Русский стоп-словарь для укорачивания (КиберЛенинка — З-2, Роспатент — Д-2).
#: Деталь приёма поиска, не общие данные проекта — поэтому здесь, в коде, а не
#: в отдельном справочнике.
RU_STOP_WORDS = frozenset(
    {
        "и",
        "в",
        "во",
        "на",
        "с",
        "со",
        "к",
        "ко",
        "от",
        "до",
        "из",
        "у",
        "о",
        "об",
        "обо",
        "по",
        "при",
        "про",
        "для",
        "без",
        "над",
        "под",
        "перед",
        "через",
        "между",
        "за",
        "а",
        "но",
        "или",
        "либо",
        "то",
        "как",
        "что",
        "чтобы",
        "это",
        "этот",
        "эта",
        "эти",
        "этих",
        "не",
        "ни",
        "же",
        "ли",
        "бы",
        "также",
        "уже",
        "ещё",
        "очень",
        "более",
        "менее",
        "самый",
    }
)
#: Символы, которые не считаются частью слова при сравнении со стоп-словарём —
#: снимаются только с краёв токена, само слово не трогаем.
_RU_PUNCT = ".,!?;:()«»\"'…—-"
_RU_TOKEN = re.compile(r"\S+")

#: Английский стоп-словарь (arXiv — диагноз Э2-Ж): формулировка длиннее
#: `PHRASE_WORD_LIMIT` уходит булевым `AND` всех термов и почти никогда не
#: встречается в одном препринте целиком.
EN_STOP_WORDS = frozenset(
    {"the", "and", "for", "with", "from", "that", "this", "are", "was", "of", "in", "on", "to", "a", "an"}
)
_EN_WORD = re.compile(r"[A-Za-z0-9\-]+")


def shorten_ru_query(text: str, *, word_limit: int) -> str:
    """Первые `word_limit` содержательных слов русской формулировки — детерминированно.

    Не модель и не эвристика по частотности: маленький фиксированный
    стоп-словарь и «первые N слов после фильтра» — один и тот же вход всегда
    даёт один и тот же короткий запрос, порядок слов исходной формулировки
    сохраняется. Если вся формулировка состоит из стоп-слов (редкость, но
    честность важнее) — короче добросовестно не сделать, отдаём как есть.
    """
    tokens = _RU_TOKEN.findall(text)
    content = [token for token in tokens if token.strip(_RU_PUNCT).lower() not in RU_STOP_WORDS]
    if not content:
        content = tokens
    return " ".join(content[:word_limit])


def english_content_words(text: str) -> list[str]:
    """Содержательные слова английской формулировки: нижний регистр, короткие
    (< 3 букв) и стоп-слова отсеяны, порядок исходного текста сохранён."""
    words = [word.lower() for word in _EN_WORD.findall(text)]
    return [word for word in words if len(word) >= 3 and word not in EN_STOP_WORDS]
