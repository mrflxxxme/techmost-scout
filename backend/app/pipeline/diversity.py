"""Разнообразие выдачи: составной признак одной разработки и склейка заготовок
карточек до их платной сборки (З-6, РЕШ-132 п. 2).

Зачем. Заказчик получает несколько карточек об одной и той же разработке и
думает, что у него несколько вариантов. Замерено на двух прогонах: в
нефтегазе (`E2B-gate-нефтегаз.md`) четыре карточки из шести на деле описывали
одну технологию (мембранная внутрискважинная сепарация) разными словами, а в
фарме (`E2V-gate-фарма.md:207`) отчёт сам признал, что карточки 3 и 4 «судя по
всему» — одна разработка. Единственная существовавшая склейка
(`selection.py:group_for_cards`) работает по точной строке организации, а у
реального дубля Э2-В организация названа лишь у одной карточки из двух —
признак, построенный на ней одной, такой случай не ловит по построению.

Порог сходства заголовков (см. `TITLE_SIMILARITY_THRESHOLD`) подобран не
«чтобы получилось красиво», а по фактическим данным двух прогонов — расчёт и
вывод по обеим сторонам приведены в отчёте задачи З-6, а не в этом модуле:
модуль остаётся чистыми функциями без сети и без вывода."""

from __future__ import annotations

import re

from app.schemas import Candidate, ScoredCandidate

#: Порог доли общих значимых слов нормализованных заголовков. Подобран по
#: реальным заготовкам двух воротных прогонов: карточки 1 и 5 отчёта Э2-В
#: (`E2V-gate-фарма.md:33,170`, разные разработки на одну тему УЗИ-диагностики
#: супоросности) делят 4 из 7 значимых слов — доля 4/7 ≈ 0,571. Порог обязан
#: держать эту пару разделённой, поэтому взят строго выше — 0,6. Ниже этого
#: порога любая пара карточек на одну широкую тему схлопывалась бы в одну,
#: выше — реальный дубль (карточки 3 и 4 того же отчёта, `:103` и `:137`,
#: доля 0,182) под общий признак попадает не через заголовок, а через то, что
#: это буквально одна работа: у него в задаче `raw_id`/DOI и заголовок
#: намеренно совпадают — см. `tests/test_diversity.py`.
TITLE_SIMILARITY_THRESHOLD = 0.6

#: Короткие служебные слова, не несущие различающего смысла для сравнения
#: заголовков. Список умышленно короткий: любое значимое слово технической
#: темы (материал, метод, показатель) обязано остаться в сравнении.
_STOPWORDS = frozenset(
    {
        "и", "в", "на", "по", "с", "со", "для", "от", "из", "о", "об", "к", "у",
        "до", "за", "при", "или", "не", "что", "это", "как", "а", "но", "же",
        "то", "так", "чем", "их", "его", "её",
    }
)

#: Организационно-правовые формы, которые не различают организации по сути:
#: одна и та же лаборатория пишется то с формой, то без неё. Только сами
#: формы (включая «во» из аббревиатуры «ФГБОУ ВО» — «высшего образования»), не
#: содержательные слова названия вроде «институт»/«университет»: список — не
#: словарь всех форм ГК РФ, а те, что фактически встречались в выдачах
#: (§0.1 SPEC — не разворачивать признак сверх подтверждённой пользы).
_ORG_LEGAL_FORMS = frozenset(
    {
        "фгбоу", "фгбну", "фгбу", "фгуп", "гбоу", "гбу", "гуп", "мооо",
        "ооо", "оао", "зао", "пао", "ао", "ип", "нии", "во",
    }
)

_WORD_RE = re.compile(r"[\w\-]+", re.UNICODE)


def _normalize_org(org: str | None) -> str:
    """Нормализовать организацию: нижний регистр, без адресного хвоста после
    запятой, без организационно-правовой формы.

    Хвост после запятой отсекается целиком: «Институт X, г. Пермь» и просто
    «Институт X» обязаны совпасть, а «Институт X» и «Институт Y, г. Пермь» —
    не совпасть по одному городу.
    """
    if not org:
        return ""
    head = org.split(",")[0].strip().lower()
    words = [w for w in _WORD_RE.findall(head) if w not in _ORG_LEGAL_FORMS]
    return " ".join(words)


def _canonical_url(url: object) -> str:
    """Канонический адрес: без схемы, без `www.`, без завершающего слэша."""
    text = str(url).strip().lower()
    for prefix in ("https://", "http://"):
        if text.startswith(prefix):
            text = text[len(prefix) :]
            break
    if text.startswith("www."):
        text = text[len("www.") :]
    return text.rstrip("/")


def _significant_words(title: str) -> set[str]:
    """Множество значимых слов заголовка: нижний регистр, без коротких
    служебных слов и однобуквенных обрывков."""
    words = (w for w in _WORD_RE.findall(title.lower()) if w not in _STOPWORDS and len(w) > 2)
    return set(words)


def _title_similarity(a: str, b: str) -> float:
    """Доля общих значимых слов (индекс Жаккара). Пустой заголовок ни с чем не
    совпадает — так пустая строка не создаёт ложных совпадений."""
    wa, wb = _significant_words(a), _significant_words(b)
    if not wa or not wb:
        return 0.0
    return len(wa & wb) / len(wa | wb)


def _same_raw_id(a: Candidate, b: Candidate) -> bool:
    """Совпал нормализованный идентификатор (raw_id/DOI).

    Нормализация уже есть в `Candidate.dedup_key` (`schemas.py:165-182`) —
    используем её, не переписывая: `dedup_key` без `raw_id` тихо падает на
    нормализованный заголовок, и тогда эта проверка задвоила бы четвёртую
    (сравнение заголовков) под чужим именем. Поэтому раньше вызова требуем
    `raw_id` на **обеих** сторонах.
    """
    if not a.raw_id or not b.raw_id:
        return False
    return a.dedup_key() == b.dedup_key()


def _same_url(a: Candidate, b: Candidate) -> bool:
    """Совпал канонический адрес."""
    return _canonical_url(a.url) == _canonical_url(b.url)


def _same_org(a: Candidate, b: Candidate) -> bool:
    """Совпала нормализованная организация. Пустая организация ни с чем не
    совпадает ни с другой пустой, ни сама с собой — иначе два кандидата без
    указанной организации считались бы одной разработкой просто по факту
    отсутствия данных."""
    norm_a, norm_b = _normalize_org(a.org), _normalize_org(b.org)
    if not norm_a or not norm_b:
        return False
    return norm_a == norm_b


def is_same_development(a: Candidate, b: Candidate) -> bool:
    """Составной признак одной разработки: истинно, если выполнено хотя бы
    одно из четырёх условий (raw_id/DOI, канонический адрес, организация,
    сходство заголовков). Один признак из четырёх — сознательно: у реального
    дубля Э2-В организация есть только с одной стороны, и признак, построенный
    на ней одной, этот случай не ловит по построению.
    """
    return (
        _same_raw_id(a, b)
        or _same_url(a, b)
        or _same_org(a, b)
        or _title_similarity(a.title, b.title) >= TITLE_SIMILARITY_THRESHOLD
    )


def _groups_are_same_development(a: list[ScoredCandidate], b: list[ScoredCandidate]) -> bool:
    """Две заготовки карточки — одна разработка, если хотя бы одна пара их
    кандидатов удовлетворяет составному признаку."""
    return any(is_same_development(x.candidate, y.candidate) for x in a for y in b)


def merge_duplicate_groups(groups: list[list[ScoredCandidate]]) -> list[list[ScoredCandidate]]:
    """Склеить заготовки карточек, признанные одной разработкой.

    Порядок групп на входе сохраняется по лучшей оценке (`group_for_cards`
    сортирует по максимальному `total` уже до вызова этой функции): поглощает
    всегда группа, встреченная раньше, а раньше в отсортированном списке
    стоит группа с оценкой не ниже поглощаемой. Внутренний состав групп при
    этом не переупорядочивается — карточку по-прежнему пишет модель по
    объединённым подтверждениям, а не код по эвристике (инвариант №1).
    """
    merged: list[list[ScoredCandidate]] = []
    for group in groups:
        target = next((existing for existing in merged if _groups_are_same_development(existing, group)), None)
        if target is None:
            merged.append(list(group))
        else:
            target.extend(group)
    return merged
