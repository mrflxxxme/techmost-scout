from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

HERE = Path(__file__).parent
FONT = "PT Serif"


def base_doc() -> Document:
    doc = Document()
    s = doc.sections[0]
    s.page_width, s.page_height = Cm(21.0), Cm(29.7)
    s.left_margin, s.right_margin = Cm(2.0), Cm(1.5)
    s.top_margin, s.bottom_margin = Cm(1.4), Cm(1.2)
    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = Pt(10)
    normal.paragraph_format.space_after = Pt(5)
    normal.paragraph_format.line_spacing = 1.0
    return doc


def para(doc, text, *, bold=False, size=10, align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=5):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    run = p.add_run(text)
    run.font.name = FONT
    run.font.size = Pt(size)
    run.bold = bold
    return p


def head(doc, text):
    para(doc, text, bold=True, size=10.5, align=WD_ALIGN_PARAGRAPH.LEFT, after=2)


def title(doc, subtitle):
    para(doc, "СПРАВКА", bold=True, size=12.5, align=WD_ALIGN_PARAGRAPH.CENTER, after=1)
    para(doc, subtitle, bold=True, size=10.5, align=WD_ALIGN_PARAGRAPH.CENTER, after=7)


